export function learningSubject(id='chemistry'){
  if(!Object.hasOwn(LEARNING_SUBJECTS,id))throw new RangeError('Unknown learning subject');
  return LEARNING_SUBJECTS[id];
}
export function subjectForCourse(course){return Object.values(LEARNING_SUBJECTS).find(s=>s.root===course?.routeRoot)||LEARNING_SUBJECTS.chemistry;}
export function subjectForPath(path){const root=String(path||'').replace(/^#/,'').split('/')[0];return Object.values(LEARNING_SUBJECTS).find(s=>s.root===root)||LEARNING_SUBJECTS.chemistry;}
